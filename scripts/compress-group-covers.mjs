// Build group-cover registry from public/group-covers/{slug}/{i}.webp.
// Resizes to 256px circle thumbs and emits LQIP blurs.
import sharp from 'sharp';
import { readdirSync, statSync, writeFileSync } from 'fs';
import { join } from 'path';

const ROOT = 'public/group-covers';
const slugs = readdirSync(ROOT).filter(d => statSync(join(ROOT, d)).isDirectory()).sort();

const out = {};
let totalKB = 0;
for (const slug of slugs) {
  const dir = join(ROOT, slug);
  const webps = readdirSync(dir).filter(f => /^\d+\.webp$/.test(f)).sort();
  if (webps.length === 0) continue;
  const blur = [];
  for (const f of webps) {
    const src = join(dir, f);
    const buf = await sharp(src).resize(256, 256, { fit: 'cover' }).webp({ quality: 70, effort: 6 }).toBuffer();
    writeFileSync(src, buf);
    totalKB += buf.length / 1024;
    const b = await sharp(src).resize(20, 20, { fit: 'cover' }).webp({ quality: 30 }).toBuffer();
    blur.push(`data:image/webp;base64,${b.toString('base64')}`);
  }
  out[slug] = { count: webps.length, blur };
}

const lines = [
  '// AUTO-GENERATED by scripts/compress-group-covers.mjs.',
  'export interface GroupCover { count: number; blur: string[] }',
  '',
  'export const GROUP_COVERS: Record<string, GroupCover> = {',
];
for (const slug of Object.keys(out).sort()) {
  const blurs = out[slug].blur.map(b => `"${b}"`).join(', ');
  lines.push(`  "${slug}": { count: ${out[slug].count}, blur: [${blurs}] },`);
}
lines.push(
  '};',
  '',
  'export const groupCoverUrl = (slug: string, i: number): string =>',
  '  `/group-covers/${slug}/${i + 1}.webp`;',
  '',
);
writeFileSync('src/data/group-covers.ts', lines.join('\n'));
console.log(`Compressed ${slugs.length} groups. Total webp: ${Math.round(totalKB)} KB`);
